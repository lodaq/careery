import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, expect, it, vi } from 'vitest';
import { readRecord, readWorkspace, updateRecord, updateWorkspace } from '../../lib/storage';
import { copyProfile, copyResume, emptyRecord, emptyWorkspace } from '../../lib/types';
import { createResume, saveResume, deleteResume, resumeRevision, sortResumes } from './resume-data';
let directory: string;
afterEach(async () => { vi.unstubAllEnvs(); vi.useRealTimers(); if (directory) await rm(directory, { recursive: true, force: true }); });
it('creates independent Profile and blank Resumes, edits and moves without changing sources, rejects stale saves and deletes', async () => {
  directory = await mkdtemp(join(tmpdir(), 'careery-resume-')); vi.stubEnv('CAREERY_DATA_DIR', directory);
  await updateRecord((record) => { record.basics.name.en = 'Original'; record.entries.push({ id: 'skill-1', kind: 'skills', name: { en: 'TypeScript' } }); });
  const record = await readRecord(), profile = copyProfile(record, 'profile-1', 'Developer', ['skill-1']);
  await updateWorkspace((workspace) => { workspace.profiles.push(profile); workspace.lastLanguage = 'ar'; });
  const form = new FormData(); form.set('name', 'First'); form.set('profileId', profile.id);
  expect((await createResume(form)).id).toBeDefined();
  let resume = (await readWorkspace()).resumes[0];
  expect(resume.entries).toEqual(profile.entries); expect(resume.language).toBe('ar');
  const edit = new FormData(); edit.set('_revision', resumeRevision(resume)); edit.set('resumeName', 'Tailored'); edit.set('language', 'en'); edit.set('profileId', ''); edit.set('name.en', 'Local');
  for (const kind of resume.sectionOrder) edit.append('sectionOrder', kind);
  edit.append('entryId', 'skill-1'); edit.set('skill-1.kind', 'skills'); edit.set('skill-1.name.en', 'Advanced TypeScript'); edit.append('hiddenEntryId', 'skill-1');
  expect((await saveResume(resume.id, edit)).revision).toBeDefined();
  expect((await saveResume(resume.id, edit)).error).toContain('changed');
  const workspace = await readWorkspace(); resume = workspace.resumes[0];
  expect(resume).toMatchObject({ name: 'Tailored', profileId: null, hiddenEntryIds: ['skill-1'], basics: { name: { en: 'Local' } } });
  expect(workspace.profiles[0]).toEqual(profile); expect(await readRecord()).toEqual(record); expect(workspace.lastLanguage).toBe('en');
  await updateWorkspace((current) => { current.lastLanguage = 'ar'; });
  edit.set('_revision', resumeRevision(resume));
  expect((await saveResume(resume.id, edit)).revision).toBeDefined();
  expect((await readWorkspace()).lastLanguage).toBe('ar');
  form.delete('profileId'); expect((await createResume(form)).id).toBeDefined();
  expect((await readWorkspace()).resumes[1].entries).toEqual([]);
  const deletion = new FormData(); deletion.set('id', resume.id); deletion.set('_revision', 'stale-revision');
  expect((await deleteResume(deletion)).error).toBeDefined();
  deletion.set('_revision', resumeRevision(resume)); expect((await deleteResume(deletion)).success).toBe(true);
  expect((await readWorkspace()).resumes).toHaveLength(1);
});

it('sorts recent edits first while preserving legacy and equal-date order without mutating storage', () => {
  const resume = copyResume(emptyRecord(), emptyWorkspace(), 'old', 'Old');
  const entries = [resume, { ...resume, id: 'newer', updatedAt: '2026-10-25T12:00:00.000Z' }, { ...resume, id: 'older', updatedAt: '2026-10-24T12:00:00.000Z' }, { ...resume, id: 'legacy' }, { ...resume, id: 'equal', updatedAt: '2026-10-25T12:00:00.000Z' }, { ...resume, id: 'invalid', updatedAt: 'not-a-date' }];
  expect(sortResumes(entries).map((item) => item.id)).toEqual(['newer', 'equal', 'older', 'old', 'legacy', 'invalid']);
  expect(entries.map((item) => item.id)).toEqual(['old', 'newer', 'older', 'legacy', 'equal', 'invalid']);
});
it('timestamps real changes and leaves a no-op save at its previous edit time', async () => {
  vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-10-25T12:00:00Z'));
  directory = await mkdtemp(join(tmpdir(), 'careery-edit-time-')); vi.stubEnv('CAREERY_DATA_DIR', directory);
  const form = new FormData(); form.set('name', 'Test'); const created = await createResume(form);
  if (!created.id) throw new Error(created.error);
  let resume = (await readWorkspace()).resumes[0]; expect(resume.updatedAt).toBe('2026-10-25T12:00:00.000Z');
  const unchanged = new FormData(); unchanged.set('resumeName', 'Test'); unchanged.set('language', 'en'); unchanged.set('_revision', resumeRevision(resume));
  for (const kind of resume.sectionOrder) unchanged.append('sectionOrder', kind);
  vi.setSystemTime(new Date('2026-10-25T12:30:00Z'));
  expect((await saveResume(created.id, unchanged)).revision).toBe(resumeRevision(resume));
  const edit = new FormData(); edit.set('resumeName', 'Changed'); edit.set('language', 'en'); edit.set('headline.en', 'Headline');
  for (const kind of resume.sectionOrder) edit.append('sectionOrder', kind);
  vi.setSystemTime(new Date('2026-10-25T13:00:00Z')); edit.set('_revision', resumeRevision(resume));
  expect((await saveResume(created.id, edit)).revision).toBeDefined();
  resume = (await readWorkspace()).resumes[0]; expect(resume.updatedAt).toBe('2026-10-25T13:00:00.000Z');
  vi.setSystemTime(new Date('2026-10-25T14:00:00Z')); edit.set('_revision', resumeRevision(resume));
  expect((await saveResume(resume.id, edit)).revision).toBe(resumeRevision(resume));
  expect((await readWorkspace()).resumes[0].updatedAt).toBe('2026-10-25T13:00:00.000Z');
});
