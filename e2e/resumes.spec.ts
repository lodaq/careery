import { execFileSync } from 'node:child_process';
import { test, expect } from '@playwright/test';
test('creates, edits, moves and deletes a Resume with durable independent content', async ({ page }) => {
  execFileSync(process.execPath, ['scripts/seed-demo.mjs'], { env: { ...process.env, CAREERY_DATA_DIR: process.env.CAREERY_E2E_DATA_DIR } });
  await page.goto('/resumes/demo-resume-1');
  await expect(page.getByLabel('Resume name', { exact: true })).toHaveValue(/demo/);
  await page.goto('/unfiled');
  await page.getByRole('button', { name: 'Create Resume', exact: true }).click();
  await page.getByLabel('New Resume name', { exact: true }).fill('Browser tailored Resume');
  await page.getByRole('dialog').getByRole('button', { name: 'Create Resume', exact: true }).click();
  await expect(page).toHaveURL(/\/resumes\//);
  const main = page.getByRole('main');
  await main.getByLabel('Resume name', { exact: true }).fill('Browser edited Resume');
  await main.getByRole('button', { name: 'Personal info', exact: true }).click();
  await main.getByLabel('Headline', { exact: true }).fill('Independent headline');
  await main.getByRole('button', { name: 'Resume settings', exact: true }).click();
  await main.getByLabel('Language', { exact: true }).selectOption('ar');
  await main.getByRole('button', { name: /Choose content/ }).click();
  await main.getByText('Browse 80 available entries', { exact: true }).click();
  await main.getByRole('checkbox', { name: 'TypeScript (skills)', exact: true }).check();
  await main.getByRole('button', { name: /^Skills/ }).click();
  await main.locator('[data-slot="collapsible"].entry-editor > [data-slot="collapsible-trigger"]').click();
  await main.getByLabel('Skill', { exact: true }).fill('Resume-only TypeScript');
  await main.getByRole('button', { name: 'Save now / retry' }).click();
  await expect(main.getByRole('status')).toHaveText('Saved');
  await page.reload();
  await expect(page.getByLabel('Resume name', { exact: true })).toHaveValue('Browser edited Resume');
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('ar');
  await page.getByRole('button', { name: /^Skills/ }).click();
  await page.locator('[data-slot="collapsible"].entry-editor > [data-slot="collapsible-trigger"]').click();
  await expect(page.getByLabel('Skill', { exact: true })).toHaveValue('Resume-only TypeScript');
  await page.getByRole('button', { name: 'Resume settings', exact: true }).click();
  await page.getByLabel('Move to', { exact: true }).selectOption('demo-profile-1');
  await page.getByRole('button', { name: 'Save now / retry' }).click();
  await expect(page.getByRole('status')).toHaveText('Saved');
  await page.getByRole('button', { name: 'Personal info', exact: true }).click();
  await expect(page.getByLabel('Headline', { exact: true })).toHaveValue('Independent headline');
  await page.goto('/profiles/demo-profile-1');
  await expect(page.getByRole('link', { name: 'Browser edited Resume', exact: true })).toBeVisible();
  const item = page.getByRole('listitem').filter({ hasText: 'Browser edited Resume' });
  await item.getByRole('button', { name: 'Delete Resume', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Browser edited Resume', exact: true })).toHaveCount(0);
});
