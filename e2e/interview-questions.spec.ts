import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

test('questions support tags, frequency, practice recovery, undo, and preserved daily history', async ({ page }) => {
  await page.goto('/interview-questions');
  await expect(page.getByRole('button', { name: 'Add question', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Manage tags', exact: true }).click();
  await page.getByRole('textbox', { name: 'New tag name', exact: true }).fill('Interview test tag');
  await page.getByRole('button', { name: 'Create tag', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Rename tag Interview test tag', exact: true })).toBeVisible();
  const renameForm = page.locator('form').filter({ has: page.getByRole('textbox', { name: 'Rename tag Interview test tag', exact: true }) });
  await renameForm.getByRole('textbox').fill('Practice test tag');
  await renameForm.getByRole('button', { name: 'Rename', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Rename tag Practice test tag', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Manage tags', exact: true }).click();
  await page.getByRole('button', { name: 'Add question', exact: true }).click();
  await page.getByLabel('Question', { exact: true }).fill('A persistent practice question?');
  await page.getByLabel('Answer', { exact: true }).fill('A specific answer to recall.');
  await page.getByLabel('Times asked in interviews', { exact: true }).fill('9');
  const editor = page.locator('form').filter({ has: page.getByLabel('Answer', { exact: true }) });
  await editor.getByRole('checkbox', { name: 'Practice test tag', exact: true }).check();
  await editor.getByRole('checkbox', { name: 'Technical', exact: true }).check();
  await page.getByRole('button', { name: 'Save question', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Question saved.');
  await page.getByRole('searchbox').fill('specific answer to recall');
  const row = page.getByRole('row').filter({ has: page.getByRole('button', { name: 'A persistent practice question?', exact: true }) });
  await expect(row.getByRole('cell', { name: '9', exact: true })).toBeVisible();
  await page.getByRole('checkbox', { name: 'Practice test tag', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Behavioral', exact: true }).check();
  await expect(row).toBeVisible();
  await page.getByRole('button', { name: 'Practice (1)', exact: true }).click();
  const practice = page.getByRole('region', { name: 'Practice session', exact: true });
  await expect(practice.getByText('A specific answer to recall.', { exact: true })).toHaveCount(0);
  await practice.getByRole('button', { name: 'Reveal answer', exact: true }).click();
  await practice.getByRole('button', { name: /^Good/ }).click();
  await expect(practice.getByText(/1 saved attempts/)).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Resume practice', exact: true }).click();
  await practice.getByRole('button', { name: 'Undo last rating', exact: true }).click();
  await expect(practice.getByText(/0 saved attempts/)).toBeVisible();
  await practice.getByRole('button', { name: 'Reveal answer', exact: true }).click();
  await practice.getByRole('button', { name: /^Easy/ }).click();
  await expect(practice.getByText('Session complete', { exact: true })).toBeVisible();
  await practice.getByRole('button', { name: 'End session', exact: true }).click();
  await page.getByRole('button', { name: 'Activity calendar', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Practice activity' }).getByText('1 distinct questions · 1 attempts', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete: A persistent practice question?', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(page.getByRole('button', { name: 'A persistent practice question?', exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Practice activity' }).getByText('A persistent practice question?', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Manage tags', exact: true }).click();
  await page.getByRole('button', { name: 'Delete tag Practice test tag', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Rename tag Practice test tag', exact: true })).toHaveCount(0);
});

test('question table fits mobile and initial JavaScript stays within budget', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/interview-questions');
  await expect(page.getByRole('button', { name: 'Add question', exact: true })).toBeEnabled();
  await page.waitForLoadState('networkidle');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  const scripts = await page.evaluate(() => [...new Set(performance.getEntriesByType('resource').map((entry) => new URL(entry.name).pathname).filter((path) => path.startsWith('/_next/static/') && path.endsWith('.js')))]);
  const sizes = await Promise.all(scripts.map(async (path) => gzipSync(await readFile(join('.next-build', path.replace('/_next/', '')))).length));
  const bytes = sizes.reduce((sum, size) => sum + size, 0);
  console.log(`Interview questions: ${bytes} gzip bytes of initial JavaScript`);
  expect(bytes).toBeLessThanOrEqual(185000);
});
