import { test, expect } from '@playwright/test';
import { gzipSync } from 'node:zlib';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { copyResume, emptyRecord, emptyWorkspace } from '../src/lib/types';

test('live preview, Arabic fallback, saved PDF downloads, long and oversized entries', async ({ page, request }) => {
  const directory = process.env.CAREERY_E2E_DATA_DIR;
  if (!directory) throw new Error('Missing isolated test directory');
  const record = emptyRecord(); record.basics.name = { en: 'Preview verification', ar: 'اختبار المعاينة' }; record.basics.email = 'person@example.com'; record.basics.links = [{ label: 'Portfolio', url: 'https://example.com' }];
  const workspace = emptyWorkspace(), short = copyResume(record, workspace, 'pdf-short', 'Short Resume');
  short.entries.push({ id: 'skill', kind: 'skills', name: { en: 'TypeScript' } }); short.language = 'ar';
  const long = structuredClone(short); long.id = 'pdf-long'; long.language = 'en';
  long.entries = Array.from({ length: 80 }, (_, index) => ({ id: `project-${index}`, kind: 'projects', name: { en: `Project ${index}` }, description: { en: 'A useful project with meaningful results and clear communication.' }, bullets: [{ id: `bullet-${index}`, text: { en: 'Delivered a reliable result and verified the behavior with automated tests.' } }] }));
  const oversized = structuredClone(short); oversized.id = 'pdf-oversized'; oversized.language = 'en';
  oversized.entries = [{ id: 'huge-project', kind: 'projects', name: { en: 'Oversized project' }, description: { en: 'Long content is allowed to split across pages.' }, bullets: [{ id: 'long-bullet', text: { en: 'Long but meaningful achievement. '.repeat(280) } }] }];
  workspace.resumes.push(short, long, oversized);
  await writeFile(join(directory, 'career-record.json'), JSON.stringify(record));
  await writeFile(join(directory, 'workspace.json'), JSON.stringify(workspace));
  await page.goto('/resumes/pdf-short');
  const preview = page.getByRole('article', { name: 'Resume preview' });
  await expect(preview).toHaveAttribute('dir', 'rtl');
  await expect(preview.locator('mark')).toHaveText(['TypeScript']);
  await expect(preview.locator('mark[title="Missing Arabic version"]')).toHaveCount(1);
  await page.getByRole('button', { name: 'Personal info', exact: true }).click();
  await page.getByLabel('Headline', { exact: true }).fill('Latest unsaved wording');
  await expect(preview).toContainText('Latest unsaved wording');
  await page.route('**/resumes/pdf-short', (route) => route.request().method() === 'POST' ? route.abort() : route.continue());
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  await expect(page.getByRole('main').getByRole('alert')).toContainText('could not be saved');
  await expect(page.getByLabel('Headline', { exact: true })).toHaveValue('Latest unsaved wording');
  await page.unroute('**/resumes/pdf-short');
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toBe('Short Resume.pdf');
  expect(await download.failure()).toBeNull();
  await expect(page.getByTitle('Paginated Resume PDF')).toHaveCount(0);
  const downloadPath = await download.path(); if (!downloadPath) throw new Error('Missing download');
  const exportedBytes = await readFile(downloadPath);
  expect(exportedBytes.subarray(0, 5).toString()).toBe('%PDF-');
  expect([...exportedBytes.toString('latin1').matchAll(/\/Type\s*\/Page\b/g)]).toHaveLength(1);
  await page.waitForLoadState('networkidle');
  const scripts = await page.evaluate(() => [...new Set(performance.getEntriesByType('resource').map((entry) => new URL(entry.name).pathname).filter((path) => path.startsWith('/_next/static/') && path.endsWith('.js')))]);
  const bytes = (await Promise.all(scripts.map(async (path) => gzipSync(await readFile(join('.next-build', path.replace('/_next/', '')))).length))).reduce((sum, size) => sum + size, 0);
  console.log(`/resumes/[id]: ${bytes} gzip bytes of loaded JavaScript`);
  await page.goto('/render/pdf-short');
  await expect(page.getByRole('article')).toContainText('Latest unsaved wording');
  const direction = await page.locator('bdi').first().evaluate((node) => getComputedStyle(node).direction);
  expect(direction).toBe('ltr');
  await page.emulateMedia({ media: 'print' });
  expect(await page.locator('.resume-document').evaluate((node) => getComputedStyle(node).display)).toBe('block');
  const shortPdf = await request.get('/api/resumes/pdf-short/pdf');
  expect(shortPdf.ok()).toBe(true);
  expect((await shortPdf.body()).subarray(0, 5).toString()).toBe('%PDF-');
  const pages = (pdf: Buffer) => [...pdf.toString('latin1').matchAll(/\/Type\s*\/Page\b/g)].length;
  expect(pages(await shortPdf.body())).toBe(1);
  for (const id of ['pdf-long', 'pdf-oversized']) {
    const result = await request.get(`/api/resumes/${id}/pdf`);
    expect(result.ok()).toBe(true); const count = pages(await result.body()); expect(count).toBeGreaterThan(1);
    expect(Number(result.headers()['x-resume-pages'])).toBe(count);
    await page.goto(`/resumes/${id}`);
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Paginated PDF preview', exact: true })).toHaveCount(0);
    const exported = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
    expect((await exported).suggestedFilename()).toMatch(/\.pdf$/);
    await page.goto('/render/pdf-short');
  }
  const started = Date.now(); const warm = await request.get('/api/resumes/pdf-short/pdf');
  expect(warm.ok()).toBe(true); expect(Date.now() - started).toBeLessThanOrEqual(5000);
  const concurrent = await Promise.all([request.get('/api/resumes/pdf-short/pdf'), request.get('/api/resumes/pdf-short/pdf')]);
  expect(concurrent.map((result) => result.status()).sort()).toEqual([200, 503]);
  expect((await request.get('/api/resumes/pdf-short/pdf')).status()).toBe(200);
  expect(JSON.parse(await readFile(join(directory, 'workspace.json'), 'utf8')).resumes).toHaveLength(3);
  const stale = await request.get('/api/resumes/pdf-short/pdf?revision=old'); expect(stale.status()).toBe(409);
  expect((await request.get('/api/resumes/missing/pdf')).status()).toBe(404);
  expect(bytes).toBeLessThanOrEqual(180000);
});
