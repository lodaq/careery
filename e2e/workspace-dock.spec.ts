import { expect, test } from '@playwright/test';
test('header groups navigation and Settings persists the theme', async ({ page }) => {
  await page.setViewportSize({ width: 801, height: 834 });
  await page.goto('/career-record');
  const dock = page.getByRole('navigation', { name: 'Workspace' });
  await expect(dock.getByRole('link')).toHaveCount(8);
  await expect(dock.getByRole('link', { name: 'Resources', exact: true })).toBeVisible();
  await expect(dock.getByRole('link', { name: 'Interview questions', exact: true })).toBeVisible();
  await expect(dock.getByRole('link', { name: 'Home', exact: true })).toHaveCount(0);
  await dock.getByRole('link', { name: 'Profiles', exact: true }).hover();
  await expect(page.locator('[data-slot=tooltip-content][data-open]')).toHaveCount(0);
  await expect(dock.getByRole('link', { name: 'Career Record' })).toHaveAttribute('aria-current', 'page');
  const box = await dock.boundingBox();
  expect(box).not.toBeNull();
  if (!box) throw new Error('Dock is not visible');
  await expect(page.locator('header.workspace-brand').getByRole('navigation', { name: 'Workspace' })).toBeVisible();
  expect(box.y + box.height).toBeLessThanOrEqual(834);
  const header = await page.locator('header.workspace-brand').boundingBox();
  expect(header).not.toBeNull();
  if (!header) throw new Error('Header is not visible');
  expect(box.y).toBeGreaterThanOrEqual(header.y);
  expect(box.y + box.height).toBeLessThanOrEqual(header.y + header.height);
  await expect(page.locator('.workspace-dock')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Use dark mode' })).toHaveCount(0);
  await dock.getByRole('link', { name: 'Settings' }).click();
  const theme = page.getByRole('switch', { name: 'Dark mode' });
  await theme.check();
  await expect(page.locator('html')).toHaveClass(/dark/);
  await page.reload();
  await expect(page.getByRole('switch', { name: 'Dark mode' })).toBeChecked();
  await dock.getByRole('link', { name: 'Profiles', exact: true }).click();
  await page.getByRole('link', { name: /^Unfiled \(/ }).click();
  await expect(page).toHaveURL(/\/unfiled$/);
  await expect(dock.getByRole('link', { name: 'Profiles', exact: true })).toHaveAttribute('aria-current', 'page');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('link', { name: 'Careery home', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Your next chapter starts here.');
});
