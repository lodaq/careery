import { expect, test } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { emptyRecord, emptyWorkspace, copyResume } from '../src/lib/types';

// All fixtures are written to the temporary directory owned by the test server.
test('creates, selects, edits, and deletes a Profile without changing independent copies', async ({ page }) => {
  const directory = process.env.CAREERY_E2E_DATA_DIR;
  if (!directory) throw new Error('Missing isolated test directory');
  const source = emptyRecord(); source.basics.name.en = 'Profile verification';
  source.entries.push({ id: 'skill-1', kind: 'skills', name: { en: 'TypeScript', ar: 'تايب سكريبت' } });
  const sourceBytes = JSON.stringify(source, null, 2) + '\n';
  await writeFile(join(directory, 'career-record.json'), sourceBytes);
  await writeFile(join(directory, 'workspace.json'), JSON.stringify(emptyWorkspace()));
  await page.goto('/career-record');
  await expect(page.getByRole('main').getByLabel('Skill · English (required)', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to workspace', exact: true }).click();
  await page.getByRole('main').getByLabel('New Profile name', { exact: true }).fill('Web developer');
  await page.getByRole('button', { name: 'Create Profile', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Profile', exact: true })).toBeVisible();
  await expect(page.getByRole('main').getByLabel('Profile name', { exact: true })).toHaveValue('Web developer');
  const ids = await page.evaluate(() => [...document.querySelectorAll('input[id],textarea[id],main[id],section[id],h2[id]')].map((element) => element.id));
  expect(new Set(ids).size).toBe(ids.length);
  await page.getByRole('checkbox', { name: 'TypeScript (skills)', exact: true }).check();
  await expect(page.getByRole('status')).toHaveText('Saved');
  await page.getByRole('main').getByLabel('Skill · English (required)', { exact: true }).fill('Advanced TypeScript');
  await page.getByRole('main').getByLabel('Default headline · English', { exact: true }).fill('Frontend engineer');
  await page.getByRole('main').getByRole('button', { name: 'Default summary: edit Arabic version', exact: true }).click();
  await page.getByRole('main').getByLabel('Default summary · Arabic (optional)', { exact: true }).fill('مطور واجهات');
  await page.getByRole('dialog').getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('main').getByLabel('Profile name', { exact: true }).fill('Frontend development');
  await expect(page.getByRole('status')).toHaveText('Saved');
  expect(await readFile(join(directory, 'career-record.json'), 'utf8')).toBe(sourceBytes);
  const workspace = JSON.parse(await readFile(join(directory, 'workspace.json'), 'utf8'));
  const profile = workspace.profiles[0];
  expect(profile.entries[0].name.en).toBe('Advanced TypeScript');
  const resume = copyResume(source, workspace, 'prepared-resume', 'Prepared application', profile);
  workspace.resumes.push(resume);
  await writeFile(join(directory, 'workspace.json'), JSON.stringify(workspace));
  source.entries = [];
  await writeFile(join(directory, 'career-record.json'), JSON.stringify(source));
  await page.reload();
  await expect(page.getByRole('main').getByLabel('Skill · English (required)', { exact: true })).toHaveValue('Advanced TypeScript');
  await expect(page.getByRole('main').getByLabel('Default summary · Arabic (optional)', { exact: true })).toHaveValue('مطور واجهات');
  await page.getByRole('main').getByLabel('Skill · English (required)', { exact: true }).fill('Profile-only wording');
  await expect(page.getByRole('status')).toHaveText('Saved');
  expect(JSON.parse(await readFile(join(directory, 'workspace.json'), 'utf8')).resumes[0]).toEqual(resume);
  await page.waitForLoadState('networkidle');
  const scripts = await page.evaluate(() => [...new Set(performance.getEntriesByType('resource').map((entry) => new URL(entry.name).pathname).filter((path) => path.startsWith('/_next/static/') && path.endsWith('.js')))]);
  const sizes = await Promise.all(scripts.map(async (path) => gzipSync(await readFile(join('.next-build', path.replace('/_next/', '')))).length));
  const bytes = sizes.reduce((sum, size) => sum + size, 0);
  console.log(`/profiles/[id]: ${bytes} gzip bytes of loaded JavaScript`);
  expect(bytes).toBeLessThanOrEqual(180_000);
  await page.getByRole('link', { name: 'Back to workspace', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Frontend development', exact: true })).toBeVisible();
  await expect(page.getByText('1 entries · 1 Resumes', { exact: true })).toBeVisible();
  page.once('dialog', (dialog) => { expect(dialog.message()).toContain('1 Resumes will move to Unfiled'); return dialog.accept(); });
  await page.getByRole('button', { name: 'Delete Frontend development', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No profiles yet', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Unfiled (1)', exact: true }).click();
  await expect(page.getByRole('listitem').filter({ hasText: 'Prepared application' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('listitem').filter({ hasText: 'Prepared application' })).toBeVisible();
  const final = JSON.parse(await readFile(join(directory, 'workspace.json'), 'utf8'));
  expect(final.profiles).toHaveLength(0);
  expect(final.resumes).toEqual([{ ...resume, profileId: null }]);
});

test('a missing Profile renders the not-found view', async ({ page }) => {
  await page.goto('/profiles/missing-profile');
  await expect(page.getByText('This page could not be found.')).toBeVisible();
});
