import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
test('searches a large bilingual Career Record without changing saved selections', async ({ page }) => {
  const directory = process.env.CAREERY_E2E_DATA_DIR;
  if (!directory) throw new Error('Missing isolated directory');
  execFileSync(process.execPath, ['scripts/seed-demo.mjs'], { env: { ...process.env, CAREERY_DATA_DIR: directory } });
  const before = await readFile(join(directory, 'workspace.json'), 'utf8');
  await page.goto('/resumes/demo-resume-1');
  await page.getByRole('button', { name: /Choose content/ }).click();
  const picker = page.getByRole('region', { name: 'Choose from your Career Record', exact: true });
  await picker.getByText('Browse 80 available entries', { exact: true }).click();
  const checked = await picker.getByRole('checkbox', { checked: true }).count();
  await picker.getByLabel('Search Career Record').fill('TypeScript');
  await picker.getByLabel('Entry type', { exact: true }).selectOption('skills');
  await expect(picker.getByRole('checkbox')).toHaveCount(1);
  await expect(picker.getByRole('checkbox', { name: 'TypeScript (skills)', exact: true })).toBeVisible();
  await picker.getByLabel('Search Career Record').fill('no matching result');
  await expect(picker.getByText(/No matching entries/)).toBeVisible();
  await picker.getByRole('button', { name: 'Clear filters' }).click();
  await expect(picker.getByRole('checkbox')).toHaveCount(80);
  await expect(picker.getByRole('checkbox', { checked: true })).toHaveCount(checked);
  await picker.getByLabel('Search Career Record').fill('الهندسة');
  await picker.getByLabel('Entry type', { exact: true }).selectOption('skills');
  await expect(picker.getByRole('checkbox')).toHaveCount(8);
  await expect(page.getByRole('status')).toHaveText('Saved');
  await page.reload();
  expect(await readFile(join(directory, 'workspace.json'), 'utf8')).toBe(before);
});
