test('retains drafts after stale-tab save and rejects cross-origin uploads', async ({ page }) => {
  await page.goto('/applications');
  await page.getByRole('button', { name: 'Add application', exact: true }).click();
  await page.locator('main:visible').getByLabel('Company', { exact: true }).fill('Stale tab fixture');
  await page.locator('main:visible').getByLabel('Job title', { exact: true }).fill('Engineer');
  await page.getByRole('button', { name: 'Add application', exact: true }).last().click();
  await expect(page).toHaveURL(/\/applications\/[^/]+$/);
  const other = await page.context().newPage(); await other.goto(page.url());
  await page.locator('main:visible').getByLabel('Company', { exact: true }).fill('Saved change');
  await page.locator('form:visible').filter({ has: page.getByLabel('Company', { exact: true }) }).getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Saved change', exact: true })).toBeVisible();
  await other.locator('main:visible').getByLabel('Company', { exact: true }).fill('Unsaved draft');
  await other.locator('form:visible').filter({ has: other.getByLabel('Company', { exact: true }) }).getByRole('button', { name: 'Save', exact: true }).click();
  await expect(other.locator('main:visible').getByRole('alert')).toContainText('changed in another tab');
  await expect(other.locator('main:visible').getByLabel('Company', { exact: true })).toHaveValue('Unsaved draft');
  const id = new URL(page.url()).pathname.split('/').at(-1);
  const response = await page.request.post(`/api/applications/${id}/documents`, { headers: { origin: 'https://untrusted.example' }, multipart: { file: { name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('test') }, revision: '1' } });
  expect(response.status()).toBe(403);
  await other.close();
});
