import { test, expect } from '@playwright/test';
import { writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { copyResume, emptyRecord, emptyWorkspace } from '../src/lib/types';
test('customizes fonts, colors, templates and section visibility across reload and PDF rendering', async ({ page }) => {
  const directory = process.env.CAREERY_E2E_DATA_DIR;
  if (!directory) throw new Error('Missing isolated directory');
  const record = emptyRecord(); record.basics.name = { en: 'Design verification', ar: 'اختبار التصميم' };
  const workspace = emptyWorkspace(), resume = copyResume(record, workspace, 'customize-test', 'My designed Resume');
  resume.hiddenSections = ['summary'];
  resume.summary.en = 'A professional summary to verify section visibility.';
  resume.entries.push({ id: 's', kind: 'skills', name: { en: 'TypeScript' } }); workspace.resumes.push(resume);
  const sourceBytes = JSON.stringify(record);
  await writeFile(join(directory, 'career-record.json'), sourceBytes); await writeFile(join(directory, 'workspace.json'), JSON.stringify(workspace));
  await page.goto('/resumes/customize-test');
  await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await page.getByLabel('Font family').selectOption('sans');
  await page.getByRole('slider', { name: 'Body size' }).focus(); await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: 'Colors', exact: true }).click();
  await page.getByRole('button', { name: 'Use accent #814942', exact: true }).click();
  await page.getByRole('button', { name: 'Template', exact: true }).click();
  await page.getByRole('button', { name: 'Cream', exact: true }).click();
  await page.getByRole('button', { name: 'Layout', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: /Hide/ })).toHaveCount(0);
  await page.getByLabel('Resume language', { exact: true }).selectOption('ar');
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await expect(page.getByRole('status')).toHaveText('Saved');
  await page.reload(); await page.getByRole('button', { name: 'Customize', exact: true }).click();
  await expect(page.getByLabel('Font family')).toHaveValue('sans'); await expect(page.getByRole('slider', { name: 'Body size' })).toHaveAttribute('aria-valuenow', '11');
  await expect(page.getByLabel('Resume template', { exact: true })).toHaveValue('cream');
  await page.getByRole('button', { name: 'Layout', exact: true }).click(); await expect(page.getByRole('checkbox', { name: /Hide/ })).toHaveCount(0);
  await page.getByRole('button', { name: 'AI Review', exact: true }).click(); await expect(page.getByText('Resume readiness · Local checks')).toBeVisible();
  expect(await readFile(join(directory, 'career-record.json'), 'utf8')).toBe(sourceBytes);
  await page.goto('/render/customize-test');
  const document = page.getByRole('article'); await expect(document).toHaveAttribute('dir', 'rtl'); await expect(document).toHaveClass(/template-cream/);
  await expect(document.getByRole('heading', { name: 'الملخص', exact: true })).toHaveCount(0);
  expect(await document.evaluate((node) => getComputedStyle(node).fontSize)).toBe('14.6667px');
  expect(await document.locator('h1').evaluate((node) => getComputedStyle(node).color)).toBe('rgb(129, 73, 66)');
});
